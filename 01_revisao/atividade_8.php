<?php
$operacao = "+";
$num1 = 3;
$num2 = 9;

switch($operacao){
    case "+";
        echo $num1 + $num2;
        break;
    
    case "-";
        echo $num1 - $num2;
        break;

    case "*";
        echo $num1 * $num2;
        break;

    case "/";
        echo $num1 / $num2;
        break;

}
?>